"""Build the app's sourced data files from data/sources/*.json.

Inputs (all in data/sources/):
  rent_nobroker_2026-11.json   live listing stats per area and BHK
  osrm_road_distances.json     road distance + free-flow drive time (OSRM / OpenStreetMap)
  area_risk_2026-11.json       flooding and water-source ratings with evidence

Outputs:
  data/rent.js        window.DATA_RENT (replaces the old hand-written sample points)
  data/sourced.js     overrides area rents, 9 AM / 2 PM commute times and the risk layer

Commute model: TomTom Traffic Index 2025 (Bengaluru, city) defines congestion as extra
travel time over free flow. Morning rush congestion is 94.2% and the 24/7 average is
74.4%, so 9 AM time = free-flow time x 1.942 and 2 PM time = free-flow time x 1.744.

Run:  python3 scripts/build_data.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "sources")

PEAK_FACTOR = 1.942     # TomTom 2025, Bengaluru morning rush congestion 94.2%
OFFPEAK_FACTOR = 1.744  # TomTom 2025, Bengaluru 24/7 average congestion 74.4%
MIN_TRIP = 5            # minutes, for same-locality trips


def load(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return json.load(f)


rent = load("rent_nobroker_2026-11.json")
roads = load("osrm_road_distances.json")
risk = load("area_risk_2026-11.json")

# ── rent.js ────────────────────────────────────────────────────────────────
data_rent = {}
for area, by_bhk in rent["areas"].items():
    for bhk, stats in by_bhk.items():
        if not stats or stats[0] == 0:
            continue
        n, p10, p25, p50, p75, p90 = stats
        data_rent[f"{area}_{bhk}BHK"] = {
            "computed": {"median": p50, "low": p10, "high": p90, "iqr": p75 - p25,
                         "n": n, "months_old_p50": 0},
            "source": f"NoBroker live listings, {rent['pulled_on']} (n={n})",
        }

rent_js = f"""// GENERATED by scripts/build_data.py from data/sources/rent_nobroker_2026-11.json. Do not edit by hand.
// {rent['_about']}
window.DATA_RENT_SOURCE = {json.dumps(f"NoBroker live listings within 2 km of each locality, pulled {rent['pulled_on']} ({rent['total_listings']:,} listings)")};
window.DATA_DEPOSIT_MONTHS = {json.dumps(rent['deposit_months'])};
window.DATA_RENT = {json.dumps(data_rent, indent=1)};
"""
with open(os.path.join(ROOT, "data", "rent.js"), "w", encoding="utf-8") as f:
    f.write(rent_js)

# ── sourced.js ─────────────────────────────────────────────────────────────
area_over = {}
for area, by_bhk in rent["areas"].items():
    o = {"avg_rent_1bhk": by_bhk["1"][3], "avg_rent_2bhk": by_bhk["2"][3], "avg_rent_3bhk": by_bhk["3"][3]}
    peak, off, km = {}, {}, {}
    for office, r in roads[area].items():
        peak[office] = max(MIN_TRIP, round(r["freeflow_min"] * PEAK_FACTOR))
        off[office] = max(MIN_TRIP, round(r["freeflow_min"] * OFFPEAK_FACTOR))
        km[office] = r["km"]
    o["commute_to"] = peak
    o["commute_offpeak"] = off
    o["commute_km"] = km
    rk = risk["areas"][area]
    o["risk"] = {
        "waterlogging": rk["waterlogging"][0], "waterloggingEvidence": rk["waterlogging"][1],
        "waterloggingNote": rk["waterlogging"][2],
        "waterSource": rk["waterSource"][0], "waterSourceEvidence": rk["waterSource"][1],
        "waterSourceNote": rk["waterSource"][2],
        "refs": sorted(set(rk["waterlogging"][3] + rk["waterSource"][3])),
    }
    area_over[area] = o

sourced_js = f"""// GENERATED by scripts/build_data.py from data/sources/*.json. Do not edit by hand.
// Overrides the hand-estimated numbers in data/areas.js with sourced ones.
window.DATA_SOURCES = {{
  rent: {json.dumps("NoBroker live listings, " + rent['pulled_on'] + " (" + format(rent['total_listings'], ',') + " listings)")},
  commute: "Road distance and free-flow time from OpenStreetMap (OSRM), scaled by TomTom Traffic Index 2025 congestion for Bengaluru (9 AM ×1.94, 2 PM ×1.74)",
  risk: "Named flood spots and water-supply reports from Deccan Herald, The News Minute, Citizen Matters, Down To Earth, OpenCity and CGWB (2019–2025). See data/sources/area_risk_2026-11.json",
  riskRefs: {json.dumps(risk['sources'], indent=1)}
}};
window.DATA_AREA_SOURCED = {json.dumps(area_over, indent=1)};
window.DATA_AREAS.forEach(function(a) {{
  var s = window.DATA_AREA_SOURCED[a.name];
  if (!s) return;
  a.avg_rent_1bhk = s.avg_rent_1bhk; a.avg_rent_2bhk = s.avg_rent_2bhk; a.avg_rent_3bhk = s.avg_rent_3bhk;
  a.commute_to = s.commute_to; a.commute_offpeak = s.commute_offpeak; a.commute_km = s.commute_km;
  a.risk = s.risk;
}});
"""
with open(os.path.join(ROOT, "data", "sourced.js"), "w", encoding="utf-8") as f:
    f.write(sourced_js)

print(f"rent.js: {len(data_rent)} area/BHK keys; sourced.js: {len(area_over)} areas")
for a in ("Hebbal", "Yeshwanthpur", "Whitefield"):
    print(a, "rent 2BHK", area_over[a]["avg_rent_2bhk"], "| 9AM to Yeshwanthpur", area_over[a]["commute_to"]["Yeshwanthpur"])
